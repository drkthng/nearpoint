/**
 * Service-worker source generator (used by the Vite plugin in vite.config.ts at build time).
 * Pure: returns the JavaScript text of sw.js for a list of built files and a version string.
 *
 * Behaviour of the generated worker:
 * - install: pre-caches every built file (the whole app, so it works offline after the first load);
 *   it does NOT skip waiting, so an update never replaces the code under a running session.
 * - activate: deletes caches of older versions and claims clients.
 * - fetch: same-origin GET only; cache first (ignoring Vary: module scripts send Origin, static
 *   hosts may answer "Vary: Origin"), then network (and caches the response);
 *   navigations fall back to the cached index.html. Cross-origin requests are not touched.
 * - message "skip-waiting": activates a waiting update (the app asks the user first).
 */
export const CACHE_PREFIX = "nearpoint-";

export function serviceWorkerSource(files: readonly string[], version: string): string {
  if (!/^[\w.-]+$/.test(version)) throw new Error(`invalid version ${version}`);
  const list = [...new Set(files.map((f) => f.replace(/^\.?\//, "")))].filter((f) => f !== "sw.js").sort();
  if (!list.includes("index.html")) throw new Error("index.html must be pre-cached");
  return `// Generated by nearpoint's build (src/pwa/sw-source.ts). Do not edit.
const CACHE = ${JSON.stringify(CACHE_PREFIX + version)};
const FILES = ${JSON.stringify(list)};
const BASE = new URL("./", self.location).href;

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new URL(f, BASE).href))));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(${JSON.stringify(CACHE_PREFIX)}) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("message", (event) => {
  if (event.data === "skip-waiting") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, { ignoreSearch: req.mode === "navigate", ignoreVary: true });
    if (hit) return hit;
    try {
      const res = await fetch(req);
      if (res.ok && res.type === "basic") cache.put(req, res.clone());
      return res;
    } catch (e) {
      if (req.mode === "navigate") {
        const index = await cache.match(new URL("index.html", BASE).href, { ignoreVary: true });
        if (index) return index;
      }
      throw e;
    }
  })());
});
`;
}
